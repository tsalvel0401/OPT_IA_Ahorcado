const cleanedWords = [];
const seen = new Set();

for (const raw of rawWordCandidates) {
  const upper = raw.trim().toUpperCase();
  const normalized = upper
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/N\u0303/g, "Ñ");

  if (normalized.length < 7 || normalized.length > 10) {
    continue;
  }

  if (!/^[A-ZÑ]{7,10}$/.test(normalized)) {
    continue;
  }

  if (!seen.has(normalized)) {
    seen.add(normalized);
    cleanedWords.push(normalized);
  }
}

// Ensure at least 500 words
if (cleanedWords.length < 500) {
  console.error(`ERROR: Only ${cleanedWords.length} words, need at least 500!`);
  process.exit(1);
}

// Sort alphabetically for clean presentation
cleanedWords.sort((a, b) => a.localeCompare('es'));

// Format output as pure JSON file
const outDir = path.resolve('src/data');
if (!fs.existsSync(outDir)) {
  fs.mkdirSync(outDir, { recursive: true });
}

fs.writeFileSync(path.join(outDir, 'words.json'), JSON.stringify(cleanedWords, null, 2), 'utf-8');
console.log(`Successfully generated src/data/words.json with ${cleanedWords.length} valid words!`);

